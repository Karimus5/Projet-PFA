-- Prédiction du service IA et retour d'information des agents (BF16-BF20 ; classe « Prediction »
-- du diagramme de classes : une réclamation porte au plus une prédiction). Compatible PostgreSQL et H2.
--
-- outcome : APPLIED (classement automatique appliqué), LOW_CONFIDENCE (seuil non atteint),
--           UNKNOWN_CATEGORY (catégorie absente du référentiel), UNAVAILABLE (erreur, délai, service
--           arrêté, disjoncteur ouvert). Les trois derniers laissent la réclamation en NEW.
-- decision : retour de l'agent / admin sur une prédiction APPLIED : CONFIRMED ou CORRECTED (BF14) ;
--            la catégorie et le service finaux sont ceux retenus en dernier.
-- Les noms de catégorie / service sont copiés (pas de clé étrangère) : l'export de réentraînement
-- (BF20) reste lisible même si l'admin renomme ou supprime ensuite une catégorie.

CREATE TABLE ai_predictions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id            BIGINT                   NOT NULL,
    outcome             VARCHAR(20)              NOT NULL,
    failure_reason      VARCHAR(30),
    predicted_category  VARCHAR(100),
    predicted_service   VARCHAR(100),
    confidence          DOUBLE PRECISION,
    model_version       VARCHAR(20),
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    decision            VARCHAR(10),
    final_category      VARCHAR(100),
    final_service       VARCHAR(100),
    decided_by_id       BIGINT,
    decided_by_role     VARCHAR(20),
    decided_at          TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_ai_predictions_claim UNIQUE (claim_id),
    CONSTRAINT fk_ai_predictions_claim FOREIGN KEY (claim_id) REFERENCES claims (id) ON DELETE CASCADE,
    CONSTRAINT ck_ai_predictions_outcome CHECK (outcome IN ('APPLIED', 'LOW_CONFIDENCE', 'UNKNOWN_CATEGORY', 'UNAVAILABLE')),
    CONSTRAINT ck_ai_predictions_decision CHECK (decision IS NULL OR decision IN ('CONFIRMED', 'CORRECTED')),
    CONSTRAINT ck_ai_predictions_confidence CHECK (confidence IS NULL OR (confidence >= 0 AND confidence <= 1))
);
CREATE INDEX ix_ai_predictions_outcome ON ai_predictions (outcome);
CREATE INDEX ix_ai_predictions_decision ON ai_predictions (decision);

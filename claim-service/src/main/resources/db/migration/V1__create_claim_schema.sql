-- Schéma de claim-service (BF6-BF15, BF22, BF23). Compatible PostgreSQL et H2 (mode PostgreSQL, tests).
-- Les utilisateurs vivent dans auth-service (autre base) : on ne stocke ici que leurs identifiants
-- (sub du JWT) et, pour les agents, le nom saisi par l'administrateur.

-- Services de traitement (« Service » du diagramme de classes).
CREATE TABLE services (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100)             NOT NULL,
    description VARCHAR(255),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_services_name UNIQUE (name)
);

-- Catégories : chacune est « traitée par » exactement un service.
CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100)             NOT NULL,
    description VARCHAR(255),
    service_id  BIGINT                   NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_categories_name UNIQUE (name),
    CONSTRAINT fk_categories_service FOREIGN KEY (service_id) REFERENCES services (id)
);

-- Association agent ↔ service, gérée par l'administrateur (agent_id = id dans auth-service).
CREATE TABLE service_agents (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id BIGINT                   NOT NULL,
    agent_id   BIGINT                   NOT NULL,
    agent_name VARCHAR(100)             NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_service_agents UNIQUE (service_id, agent_id),
    CONSTRAINT fk_service_agents_service FOREIGN KEY (service_id) REFERENCES services (id) ON DELETE CASCADE
);
CREATE INDEX ix_service_agents_agent ON service_agents (agent_id);

CREATE TABLE claims (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title                 VARCHAR(150)             NOT NULL,
    description           VARCHAR(10000)           NOT NULL,
    status                VARCHAR(20)              NOT NULL,
    client_id             BIGINT                   NOT NULL,
    client_email          VARCHAR(255),
    assigned_agent_id     BIGINT,
    assigned_agent_name   VARCHAR(100),
    category_id           BIGINT,
    service_id            BIGINT,
    classification_source VARCHAR(10),
    confidence_score      DOUBLE PRECISION,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    version               BIGINT                   NOT NULL DEFAULT 0,
    CONSTRAINT fk_claims_category FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT fk_claims_service FOREIGN KEY (service_id) REFERENCES services (id),
    CONSTRAINT ck_claims_status CHECK (status IN
        ('NEW', 'CLASSIFIED', 'ASSIGNED', 'IN_PROGRESS', 'RESOLVED', 'CLOSED', 'REJECTED')),
    CONSTRAINT ck_claims_source CHECK (classification_source IS NULL OR classification_source IN ('MANUAL', 'AI')),
    CONSTRAINT ck_claims_confidence CHECK (confidence_score IS NULL OR (confidence_score >= 0 AND confidence_score <= 1))
);
CREATE INDEX ix_claims_client ON claims (client_id);
CREATE INDEX ix_claims_service ON claims (service_id);
CREATE INDEX ix_claims_agent ON claims (assigned_agent_id);
CREATE INDEX ix_claims_status ON claims (status);

CREATE TABLE claim_comments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id    BIGINT                   NOT NULL,
    author_id   BIGINT                   NOT NULL,
    author_role VARCHAR(20)              NOT NULL,
    content     VARCHAR(2000)            NOT NULL,
    internal    BOOLEAN                  NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_comments_claim FOREIGN KEY (claim_id) REFERENCES claims (id) ON DELETE CASCADE
);
CREATE INDEX ix_comments_claim ON claim_comments (claim_id);

CREATE TABLE status_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id    BIGINT                   NOT NULL,
    old_status  VARCHAR(20),
    new_status  VARCHAR(20)              NOT NULL,
    author_id   BIGINT                   NOT NULL,
    author_role VARCHAR(20)              NOT NULL,
    note        VARCHAR(500),
    changed_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_history_claim FOREIGN KEY (claim_id) REFERENCES claims (id) ON DELETE CASCADE
);
CREATE INDEX ix_history_claim ON status_history (claim_id);

CREATE TABLE claim_attachments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id       BIGINT                   NOT NULL,
    file_name      VARCHAR(255)             NOT NULL,
    content_type   VARCHAR(100)             NOT NULL,
    size_bytes     BIGINT                   NOT NULL,
    storage_path   VARCHAR(255)             NOT NULL,
    uploaded_by_id BIGINT                   NOT NULL,
    uploaded_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_attachments_storage UNIQUE (storage_path),
    CONSTRAINT fk_attachments_claim FOREIGN KEY (claim_id) REFERENCES claims (id) ON DELETE CASCADE
);
CREATE INDEX ix_attachments_claim ON claim_attachments (claim_id);
